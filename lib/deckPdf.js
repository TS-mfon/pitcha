import { jsPDF } from "jspdf";

/**
 * Generates an Afro-Tech styled 10-slide investor presentation deck PDF.
 * Uses landscape orientation matching pitch deck dimensions.
 *
 * @param {object} params
 * @param {string} params.idea - The startup pitch premise
 * @param {object} params.xrayData - Result from /api/xray (problemScore, marketSize, slideOutline, pitchScript, etc.)
 * @param {object} params.demoScriptData - Optional result from /api/demo-script
 */
export function generateDeckPDF({ idea, xrayData, demoScriptData }) {
  if (!xrayData) {
    throw new Error("No X-Ray analysis data available to generate PDF.");
  }

  // A4 Landscape dimensions in points: 842 pt wide x 595 pt high
  const doc = new jsPDF({
    orientation: "landscape",
    unit: "pt",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth(); // 842
  const pageHeight = doc.internal.pageSize.getHeight(); // 595

  // Pitcha Design System Colors
  const COLOR_BG = [8, 12, 20]; // #080C14 Deep Obsidian
  const COLOR_SURFACE = [15, 23, 42]; // #0F172A Slate Surface
  const COLOR_ELEVATED = [30, 41, 59]; // #1E293B Card Background
  const COLOR_BORDER = [51, 65, 85]; // #334155 Slate Border
  const COLOR_EMERALD = [16, 185, 129]; // #10B981 Naira Emerald
  const COLOR_GOLD = [245, 158, 11]; // #F59E0B Solar Gold
  const COLOR_INDIGO = [99, 102, 241]; // #6366F1 Electric Indigo
  const COLOR_CORAL = [239, 68, 68]; // #EF4444 Coral Warning
  const COLOR_WHITE = [248, 250, 252]; // #F8FAFC Heading White
  const COLOR_MUTED = [148, 163, 184]; // #94A3B8 Secondary Text

  // Helper to draw dark slide background
  function drawSlideBackground() {
    doc.setFillColor(...COLOR_BG);
    doc.rect(0, 0, pageWidth, pageHeight, "F");

    // Top accent radiant bar
    doc.setFillColor(...COLOR_INDIGO);
    doc.rect(0, 0, pageWidth, 4, "F");
  }

  // Helper to draw slide footer with branding & page number
  function drawSlideFooter(slideNum, totalSlides) {
    doc.setDrawColor(...COLOR_BORDER);
    doc.line(40, pageHeight - 35, pageWidth - 40, pageHeight - 35);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...COLOR_MUTED);
    doc.text("🚀 Pitcha • African Startup & Hackathon Pitch Accelerator", 40, pageHeight - 20);

    doc.setFont("helvetica", "bold");
    doc.text(`Slide ${slideNum} of ${totalSlides}`, pageWidth - 40, pageHeight - 20, { align: "right" });
  }

  const slides = xrayData.slideOutline || [];
  const totalSlides = 1 + slides.length + 1; // Cover + 10 Slides + Pitch Script

  // -------------------------------------------------------------
  // SLIDE 1: COVER SLIDE
  // -------------------------------------------------------------
  drawSlideBackground();

  // Subtle decorative card box in center
  doc.setFillColor(...COLOR_SURFACE);
  doc.setDrawColor(...COLOR_BORDER);
  doc.roundedRect(60, 60, pageWidth - 120, pageHeight - 120, 16, 16, "FD");

  // Cover Tag Badge
  doc.setFillColor(...COLOR_INDIGO);
  doc.roundedRect(90, 95, 160, 24, 6, 6, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(...COLOR_WHITE);
  doc.text("HACKATHON INVESTOR DECK", 100, 111);

  // App Logo
  doc.setFontSize(12);
  doc.setTextColor(...COLOR_EMERALD);
  doc.text("GENERATED BY PITCHA", pageWidth - 100, 111, { align: "right" });

  // Main Startup Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(26);
  doc.setTextColor(...COLOR_WHITE);
  const titleLines = doc.splitTextToSize(idea.trim(), pageWidth - 200);
  doc.text(titleLines.slice(0, 3), 90, 160);

  // Tagline
  doc.setFont("helvetica", "normal");
  doc.setFontSize(13);
  doc.setTextColor(...COLOR_MUTED);
  doc.text("Your AI co-founder, AI judge and AI salesman in one.", 90, 240);

  // Metric Box (Problem Score & Market)
  const scoreBoxY = 280;
  doc.setFillColor(...COLOR_ELEVATED);
  doc.setDrawColor(...COLOR_BORDER);
  doc.roundedRect(90, scoreBoxY, 200, 80, 10, 10, "FD");

  doc.setFontSize(10);
  doc.setTextColor(...COLOR_MUTED);
  doc.text("PROBLEM SCORE", 110, scoreBoxY + 28);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(26);
  doc.setTextColor(...COLOR_EMERALD);
  doc.text(`${xrayData.problemScore || 8} / 10`, 110, scoreBoxY + 62);

  // Market Snapshot Box
  doc.setFillColor(...COLOR_ELEVATED);
  doc.roundedRect(310, scoreBoxY, pageWidth - 400, 80, 10, 10, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(...COLOR_GOLD);
  doc.text("MARKET SNAPSHOT", 330, scoreBoxY + 28);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...COLOR_WHITE);
  const marketSnippet = doc.splitTextToSize(xrayData.marketSize || "African regional market opportunity", pageWidth - 440);
  doc.text(marketSnippet.slice(0, 2), 330, scoreBoxY + 48);

  drawSlideFooter(1, totalSlides);

  // -------------------------------------------------------------
  // SLIDES 2 to 11: 10 INVESTOR SLIDES
  // -------------------------------------------------------------
  slides.forEach((slide, idx) => {
    doc.addPage();
    drawSlideBackground();

    const slideNumber = idx + 1;
    const currentSlidePage = idx + 2;

    // Header Pill for Slide Number
    doc.setFillColor(...COLOR_INDIGO);
    doc.roundedRect(50, 40, 75, 26, 6, 6, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(...COLOR_WHITE);
    doc.text(`SLIDE ${slideNumber.toString().padStart(2, "0")}`, 60, 57);

    // Slide Title
    doc.setFontSize(22);
    doc.setTextColor(...COLOR_WHITE);
    doc.text(slide.title.toUpperCase(), 140, 59);

    // Slide Content Card Box
    doc.setFillColor(...COLOR_SURFACE);
    doc.setDrawColor(...COLOR_BORDER);
    doc.roundedRect(50, 85, pageWidth - 100, pageHeight - 150, 12, 12, "FD");

    // Bullet points with wrapped text and custom colored indicators
    let bulletY = 130;
    const bullets = slide.bullets || [];

    bullets.forEach((bullet, bIdx) => {
      // Emerald bullet dot
      doc.setFillColor(...COLOR_EMERALD);
      doc.circle(85, bulletY - 4, 4, "F");

      // Bullet text with line wrap
      doc.setFont("helvetica", "normal");
      doc.setFontSize(13);
      doc.setTextColor(...COLOR_WHITE);

      const wrappedLines = doc.splitTextToSize(bullet, pageWidth - 210);
      doc.text(wrappedLines, 105, bulletY);

      bulletY += (wrappedLines.length * 20) + 16;
    });

    // Special footer context per slide
    if (slide.title.toLowerCase().includes("problem") && xrayData.weakness) {
      doc.setFillColor(...COLOR_ELEVATED);
      doc.setDrawColor(...COLOR_CORAL);
      doc.roundedRect(70, pageHeight - 145, pageWidth - 140, 50, 8, 8, "FD");

      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(...COLOR_CORAL);
      doc.text("CRITICAL EXECUTION RISK / BLINDSPOT:", 85, pageHeight - 128);

      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(...COLOR_WHITE);
      const weakLines = doc.splitTextToSize(xrayData.weakness, pageWidth - 170);
      doc.text(weakLines.slice(0, 1), 85, pageHeight - 110);
    } else if (slide.title.toLowerCase().includes("solution") && xrayData.suggestion) {
      doc.setFillColor(...COLOR_ELEVATED);
      doc.setDrawColor(...COLOR_EMERALD);
      doc.roundedRect(70, pageHeight - 145, pageWidth - 140, 50, 8, 8, "FD");

      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(...COLOR_EMERALD);
      doc.text("TACTICAL 10X UNFAIR ADVANTAGE:", 85, pageHeight - 128);

      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(...COLOR_WHITE);
      const sugLines = doc.splitTextToSize(xrayData.suggestion, pageWidth - 170);
      doc.text(sugLines.slice(0, 1), 85, pageHeight - 110);
    }

    drawSlideFooter(currentSlidePage, totalSlides);
  });

  // -------------------------------------------------------------
  // FINAL SLIDE: 60-SECOND STAGE PITCH SCRIPT
  // -------------------------------------------------------------
  doc.addPage();
  drawSlideBackground();

  // Teleprompter Slide Header
  doc.setFillColor(...COLOR_GOLD);
  doc.roundedRect(50, 40, 140, 26, 6, 6, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(...COLOR_BG);
  doc.text("TELEPROMPTER", 60, 57);

  doc.setFontSize(22);
  doc.setTextColor(...COLOR_WHITE);
  doc.text("60-SECOND VERBAL STAGE SCRIPT", 210, 59);

  // Script Card Box
  doc.setFillColor(...COLOR_SURFACE);
  doc.setDrawColor(...COLOR_BORDER);
  doc.roundedRect(50, 85, pageWidth - 100, pageHeight - 150, 12, 12, "FD");

  doc.setFont("helvetica", "italic");
  doc.setFontSize(13);
  doc.setTextColor(...COLOR_WHITE);

  const scriptLines = doc.splitTextToSize(
    `"${xrayData.pitchScript || "Good morning judges..."}"`,
    pageWidth - 140
  );

  doc.text(scriptLines, 75, 125);

  drawSlideFooter(totalSlides, totalSlides);

  // -------------------------------------------------------------
  // TRIGGER DOWNLOAD IN BROWSER
  // -------------------------------------------------------------
  const sanitizedTitle = (idea.slice(0, 20) || "startup")
    .replace(/[^a-zA-Z0-9]/g, "_")
    .toLowerCase();

  doc.save(`pitcha_deck_${sanitizedTitle}.pdf`);
}
